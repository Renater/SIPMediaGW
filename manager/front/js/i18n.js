let current = 'fr';
const listeners = new Set();

export const t = () => DICTIONARIES[current];
export const lang = () => current;

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/* Translate every [data-i18n] node in a container: called on language change
   and again each time a view fragment is injected. */
export function translate(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) {
    const value = t()[node.dataset.i18n];
    if (typeof value === 'string') node.textContent = value;
  }
  // An icon button has no text: its name, read by a screen reader, is here.
  for (const node of root.querySelectorAll('[data-i18n-aria]')) {
    const value = t()[node.dataset.i18nAria];
    if (typeof value === 'string') node.setAttribute('aria-label', value);
  }
}

export function setLanguage(next) {
  current = DICTIONARIES[next] ? next : 'fr';
  document.documentElement.lang = current;
  for (const button of document.querySelectorAll('.lang button')) {
    const on = button.dataset.lang === current;
    button.classList.toggle('on', on);
    button.setAttribute('aria-pressed', String(on));
  }
  savePrefs({ lang: current });
  translate();
  // One failing listener must not stop the others: a stale view would
  // otherwise leave the current one untranslated.
  for (const listener of listeners) {
    try { listener(); } catch (error) { console.error('i18n listener failed', error); }
  }
}

export function initialLanguage() {
  const saved = loadPrefs().lang;
  if (saved) return saved;
  return (navigator.language || 'fr').toLowerCase().startsWith('en') ? 'en' : 'fr';
}
